/** 和建模工具无关的几节（打印规矩、配合尺寸、自查、好看），build123d 那个服务器也用 */
export const sharedSection = (k: "printing" | "fits" | "review" | "look"): [string, () => string] => SECTIONS[k];

export function guide(topic = ""): string {
  const t = topic.trim().toLowerCase();
  if (t === "all") return GUIDE_TOPICS.map((k) => SECTIONS[k][1]()).join("\n\n");
  if (SECTIONS[t]) return SECTIONS[t][1]();
  // 不填：基本约定 + 小函数 + 目录
  return `${SECTIONS.basics[1]()}\n\n${SECTIONS.helpers[1]()}\n\n## 还有这些（model_guide topic=…，用到就读）\n${GUIDE_TOPICS.filter((k) => k !== "basics" && k !== "helpers").map((k) => `- ${k}：${SECTIONS[k][0]}`).join("\n")}`;
}

